import { Search, Filter, AlertTriangle, ShieldAlert, WifiOff, FileText } from "lucide-react";
import { minePortfolio } from "@/data/regulatorMocks";

export function MinePortfolioTab() {
  
  const getStatusBadge = (status: string) => {
    switch(status) {
      case 'Alert Active': return <span className="px-2 py-1 bg-warning/20 text-warning text-[10px] font-bold uppercase rounded">Alert Active</span>;
      case 'Review Required': return <span className="px-2 py-1 bg-caution/20 text-caution text-[10px] font-bold uppercase rounded">Review Required</span>;
      case 'Monitoring Gap': return <span className="px-2 py-1 bg-purple-500/20 text-purple-400 text-[10px] font-bold uppercase rounded">Monitoring Gap</span>;
      case 'System Offline': return <span className="px-2 py-1 bg-slate-500/20 text-slate-400 text-[10px] font-bold uppercase rounded">Offline</span>;
      case 'Monitoring Available': return <span className="px-2 py-1 bg-safe/20 text-safe text-[10px] font-bold uppercase rounded">Monitoring Available</span>;
      default: return null;
    }
  };

  return (
    <div className="flex flex-col gap-6 h-[calc(100vh-8rem)] overflow-auto pb-8">
      <div className="flex flex-col sm:flex-row gap-3 items-start sm:items-center">
        <div>
          <h2 className="text-xl font-bold text-foreground">Mine Portfolio</h2>
          <p className="text-sm text-muted-foreground mt-1">Institutional overview of all registered monitoring sites.</p>
        </div>
        <div className="flex items-center gap-2 sm:ml-auto">
          <div className="bg-background border rounded-lg shadow-sm flex items-center px-3 py-1.5 w-64">
            <Search className="size-4 text-muted-foreground mr-2" />
            <input type="text" placeholder="Search mines or companies..." className="bg-transparent border-none outline-none text-sm w-full" />
          </div>
          <button className="flex items-center gap-2 bg-muted hover:bg-muted/80 px-3 py-1.5 rounded-lg text-sm font-semibold transition-colors border">
            <Filter className="size-4" /> Filters
          </button>
        </div>
      </div>

      <div className="bg-warning/10 border-l-4 border-warning p-4 rounded-r-lg text-sm flex items-start gap-3">
        <AlertTriangle className="size-5 text-warning shrink-0 mt-0.5" />
        <div>
          <p className="font-semibold text-warning mb-1">Disclaimer on Application Statuses</p>
          <p className="text-muted-foreground">The platform statuses listed below (e.g., "Alert Active", "Review Required") are internal software states generated by the BhuRakshak sensor network algorithms. They are designed to facilitate oversight and <strong>do not constitute official DGMS safety classifications or regulatory rulings.</strong></p>
        </div>
      </div>

      <div className="rounded-xl border bg-card shadow-sm overflow-hidden flex-1">
        <div className="overflow-x-auto">
          <table className="w-full text-sm text-left">
            <thead className="bg-muted/50 text-muted-foreground uppercase text-xs tracking-wider">
              <tr>
                <th className="px-6 py-4 font-semibold">Mine / Location</th>
                <th className="px-6 py-4 font-semibold">Company</th>
                <th className="px-6 py-4 font-semibold">Platform Status</th>
                <th className="px-6 py-4 font-semibold text-center">Alerts</th>
                <th className="px-6 py-4 font-semibold text-center">Risk Zones</th>
                <th className="px-6 py-4 font-semibold">System Health</th>
                <th className="px-6 py-4 font-semibold">Last Review</th>
                <th className="px-6 py-4 font-semibold"></th>
              </tr>
            </thead>
            <tbody className="divide-y divide-border">
              {minePortfolio.map((mine) => (
                <tr key={mine.id} className="hover:bg-muted/30 transition-colors">
                  <td className="px-6 py-4">
                    <div className="font-bold text-foreground">{mine.name}</div>
                    <div className="text-xs text-muted-foreground mt-1">{mine.coalfield}, {mine.state}</div>
                    <div className="text-[10px] font-mono text-muted-foreground mt-0.5">{mine.id}</div>
                  </td>
                  <td className="px-6 py-4 text-foreground/80 font-medium">
                    {mine.company}
                  </td>
                  <td className="px-6 py-4">
                    {getStatusBadge(mine.status)}
                    {mine.unresolvedAlerts > 0 && (
                      <div className="text-[10px] text-warning font-semibold mt-1 flex items-center gap-1">
                        <ShieldAlert className="size-3" /> {mine.unresolvedAlerts} unresolved
                      </div>
                    )}
                  </td>
                  <td className="px-6 py-4 text-center font-mono font-bold">
                    {mine.activeAlerts > 0 ? (
                      <span className="text-warning">{mine.activeAlerts}</span>
                    ) : (
                      <span className="text-muted-foreground">0</span>
                    )}
                  </td>
                  <td className="px-6 py-4 text-center font-mono font-bold">
                    {mine.highRiskZones > 0 ? (
                      <span className="text-critical">{mine.highRiskZones}</span>
                    ) : (
                      <span className="text-muted-foreground">0</span>
                    )}
                  </td>
                  <td className="px-6 py-4">
                    <div className="flex items-center gap-2">
                      {mine.status === 'System Offline' ? (
                        <WifiOff className="size-4 text-muted-foreground" />
                      ) : (
                        <div className="h-1.5 w-16 bg-muted rounded-full overflow-hidden">
                          <div className="h-full bg-safe" style={{ width: mine.health }} />
                        </div>
                      )}
                      <span className="font-mono text-xs">{mine.health}</span>
                    </div>
                    <div className="text-[10px] text-muted-foreground mt-1">Sync: {mine.lastSync}</div>
                  </td>
                  <td className="px-6 py-4 text-foreground/80 text-xs">
                    {mine.lastReview}
                  </td>
                  <td className="px-6 py-4 text-right">
                    <button className="flex items-center justify-center gap-2 px-3 py-1.5 bg-primary/10 text-primary hover:bg-primary/20 rounded font-semibold text-xs transition-colors whitespace-nowrap">
                      <FileText className="size-3.5" /> View Detail
                    </button>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </div>
    </div>
  );
}
